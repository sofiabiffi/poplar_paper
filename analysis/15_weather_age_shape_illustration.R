# Historical linear-versus-quadratic illustration, superseded by the current
# quadratic-only figure in 14_raw_paic_weather_final.R. Requires earlier fits.
.libPaths(c('poplar_paper/renv/library',.libPaths()))
library(ggplot2)
source('plot_style.R')
root <- 'poplar_paper'
m <- readRDS(file.path(root,'results/models/final_raw_paic_weather.rds'))
if(is.null(m$fits[['B|Linear age|Both']])) stop('Historical illustration: use archived prior_current_weather_models.rds rather than current quadratic-only fits. Current figures are generated by analysis 14.')
dat <- m$data
curves <- list(); comparisons <- list()
for(h in names(publication_hybrids)) {
  d <- dat[dat$hybrid_code==h,]
  linear <- m$fits[[paste(h,'Linear age','Both',sep='|')]]
  quadratic <- glm(PAIC~age_c+I(age_c^2)+rain_c+temp_c,data=d,family=Gamma('log'),control=glm.control(maxit=200))
  stopifnot(quadratic$converged)
  nd <- data.frame(age_years=seq(min(d$age_years),max(d$age_years),length.out=200),temp_c=mean(dat$temp_c),rain_c=mean(dat$rain_c))
  nd$age_c <- (nd$age_years-15)/10
  for(spec in c('Linear age','Quadratic age')) {
    fit <- if(spec=='Linear age')linear else quadratic
    curves[[paste(h,spec)]] <- data.frame(hybrid_code=h,hybrid=publication_labels(h),age_years=nd$age_years,PAIC=predict(fit,nd,type='response'),age_model=spec)
  }
  aicc <- function(f) { k<-attr(logLik(f),'df');n<-nobs(f);AIC(f)+2*k*(k+1)/(n-k-1) }
  null <- m$fits[[paste(h,'No age','No weather',sep='|')]]$deviance
  comparisons[[h]] <- data.frame(hybrid_code=h,hybrid=publication_labels(h),linear_pseudo_R2=1-linear$deviance/null,quadratic_pseudo_R2=1-quadratic$deviance/null,quadratic_minus_linear_AICc=aicc(quadratic)-aicc(linear))
}
curves <- do.call(rbind,curves); comparisons <- do.call(rbind,comparisons)
curves$hybrid <- factor(curves$hybrid,levels=unname(publication_hybrids))
curves$age_model <- factor(curves$age_model,levels=c('Linear age','Quadratic age'))
p <- ggplot(curves,aes(age_years,PAIC,colour=age_model,linetype=age_model))+
  geom_line(linewidth=1)+facet_wrap(~hybrid,ncol=2)+
  scale_colour_manual(values=c('Linear age'='#0072B2','Quadratic age'='#D55E00'),name=NULL)+
  scale_linetype_manual(values=c('Linear age'='solid','Quadratic age'='dashed'),name=NULL)+
  labs(title='What the two age terms imply for your hybrids',x='Tree age (years)',y=expression('Fitted PAIC at fixed weather'~(Mg~C~ha^{-1}~yr^{-1})),
    caption='Both models include summer rainfall and temperature, held here at the same observed mean values.\nCurves show fitted mean shapes only; uncertainty is omitted for clarity. They are not observed PAIC trajectories.\nGamma log-link model: linear age is straight on the log-mean scale, so it can curve slightly on the original PAIC scale.')+
  theme_publication(12)
stem <- file.path(root,'results/figures/weather_age_shape_illustration')
save_publication_plot(p,stem,width=9,height=6.5)
ggsave(paste0(stem,'_preview.png'),p,width=9,height=6.5,dpi=150,bg='white')
write.csv(curves,file.path(root,'results/tables/weather_age_shape_illustration.csv'),row.names=FALSE)
write.csv(comparisons,file.path(root,'results/tables/weather_age_shape_comparison.csv'),row.names=FALSE)
print(comparisons)
